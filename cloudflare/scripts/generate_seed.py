#!/usr/bin/env python3
"""Regenerate migrations/0001_init.sql from the same DataFrame literals as src/data/init_db.py."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "migrations" / "0001_init.sql"

# Literals copied from src/data/init_db.py::_write_tables
settlements = pd.DataFrame({
    "settlement_id": [f"SET{i:04d}" for i in range(1, 21)],
    "merchant_id": [f"MER{i%5+1:03d}" for i in range(20)],
    "expected_amount": [1000 + i*50 for i in range(20)],
    "settled_amount": [1000 + i*50 - (i%4)*30 for i in range(20)],
    "settlement_date": pd.date_range("2026-11-01", periods=20, freq="D"),
    "status": ["settled"]*18 + ["delayed", "mismatch"],
    "fee_rate": [0.025 + (i%3)*0.005 for i in range(20)]
})
txns = pd.DataFrame({
    "txn_id": [f"TXN{i:05d}" for i in range(1, 101)],
    "settlement_id": [f"SET{(i%20)+1:04d}" for i in range(100)],
    "amount": [50 + (i%20)*10 for i in range(100)],
    "txn_date": pd.date_range("2026-10-25", periods=100, freq="h"),
    "type": ["sale" if i%5 != 0 else "refund" for i in range(100)]
})
fee_docs = pd.DataFrame([
    {"id": "fee1", "text": "Standard merchant fee is 2.5% of gross volume. Volume tiers above $10k receive 2.2%."},
    {"id": "fee2", "text": "Settlement must occur within T+2. Delays beyond T+3 trigger investigation."},
    {"id": "fee3", "text": "Fee variance above 1.5 percentage points requires root-cause analysis and possible dispute."},
    {"id": "fee4", "text": "Refunds reduce net settlement. Expected net = gross - refunds - fees."}
])


def sql_str(value: object) -> str:
    return "'" + str(value).replace("'", "''") + "'"


lines = [
    "-- Schema + seed generated deterministically from src/data/init_db.py",
    "-- (same DataFrame literals and pandas date_range calls).",
    "-- Regenerated by: python scripts/generate_seed.py",
    "PRAGMA foreign_keys = ON;",
    "",
    "DROP TABLE IF EXISTS transactions;",
    "DROP TABLE IF EXISTS fee_documents;",
    "DROP TABLE IF EXISTS settlements;",
    "",
    "CREATE TABLE settlements (",
    "  settlement_id   TEXT PRIMARY KEY,",
    "  merchant_id     TEXT NOT NULL,",
    "  expected_amount INTEGER NOT NULL,",
    "  settled_amount  INTEGER NOT NULL,",
    "  settlement_date TEXT NOT NULL,  -- YYYY-MM-DD (pandas midnight dates)",
    "  status          TEXT NOT NULL,",
    "  fee_rate        REAL NOT NULL",
    ");",
    "",
    "CREATE TABLE transactions (",
    "  txn_id         TEXT PRIMARY KEY,",
    "  settlement_id  TEXT NOT NULL REFERENCES settlements(settlement_id),",
    "  amount         INTEGER NOT NULL,",
    "  txn_date       TEXT NOT NULL,  -- YYYY-MM-DD HH:MM:SS",
    "  type           TEXT NOT NULL",
    ");",
    "",
    "CREATE TABLE fee_documents (",
    "  id   TEXT PRIMARY KEY,",
    "  text TEXT NOT NULL",
    ");",
    "",
    "INSERT INTO settlements (settlement_id, merchant_id, expected_amount, settled_amount, settlement_date, status, fee_rate) VALUES",
]
srows = []
for r in settlements.itertuples(index=False):
    date = r.settlement_date.strftime("%Y-%m-%d")
    srows.append(
        f"  ({sql_str(r.settlement_id)}, {sql_str(r.merchant_id)}, {int(r.expected_amount)}, "
        f"{int(r.settled_amount)}, {sql_str(date)}, {sql_str(r.status)}, {repr(float(r.fee_rate))})"
    )
lines.append(",\n".join(srows) + ";")
lines.append("")
lines.append("INSERT INTO transactions (txn_id, settlement_id, amount, txn_date, type) VALUES")
trows = []
for r in txns.itertuples(index=False):
    dt = r.txn_date.strftime("%Y-%m-%d %H:%M:%S")
    trows.append(
        f"  ({sql_str(r.txn_id)}, {sql_str(r.settlement_id)}, {int(r.amount)}, {sql_str(dt)}, {sql_str(r.type)})"
    )
lines.append(",\n".join(trows) + ";")
lines.append("")
lines.append("INSERT INTO fee_documents (id, text) VALUES")
frows = [f"  ({sql_str(r.id)}, {sql_str(r.text)})" for r in fee_docs.itertuples(index=False)]
lines.append(",\n".join(frows) + ";")
lines.append("")
OUT.write_text("\n".join(lines) + "\n")
print(f"Wrote {OUT}")
