function httpApi(partial: Omit<ConnectorDef, "sync_mode" | "fields" | "probe_name"> & { fields?: CatalogField[]; probe_name?: string; extra_fields?: CatalogField[] }): ConnectorDef {
  const { fields, extra_fields, probe_name, ...rest } = partial;
  return {
    ...rest,
    sync_mode: "http",
    probe_name: probe_name ?? "Authenticated HTTPS GET",
    fields: [
      f("base_url", "API base URL", "url", { required: true }),
      ...(extra_fields ?? []),
      ...(fields ?? AUTH_FIELDS),
    ],
  };
}

function fileFmt(partial: Omit<ConnectorDef, "sync_mode" | "relay"> & { parser: string }): ConnectorDef {
  return {
    sync_mode: "file",
    relay: "none",
    ...partial,
  };
}

function planned(partial: Omit<ConnectorDef, "sync_mode">): ConnectorDef {
  return { sync_mode: "planned", parser: "planned", ...partial };
}

